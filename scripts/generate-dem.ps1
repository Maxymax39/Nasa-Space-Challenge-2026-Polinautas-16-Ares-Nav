# Generates assets/data/jezero_dem_sample.json
#
# IMPORTANT: this is a MODELED elevation grid, not a PDS product. It is a
# parametric approximation of the western Jezero delta region whose datum and
# relief are anchored to published MOLA / HiRISE-CTX DTM values (crater floor
# near -2565 m, delta top near -2495 m). Replace it with a resampled
# JEZ_hirise_soc_006_DTM_MOLAtopography_DeltaGeoid_1m product for flight use.
#
# Usage:  powershell -ExecutionPolicy Bypass -File scripts/generate-dem.ps1

$ErrorActionPreference = 'Stop'
$ncols = 180; $nrows = 120
$west = 77.33; $east = 77.49; $south = 18.42; $north = 18.52
$widthKm = 9.0; $heightKm = 5.93

function Smooth([double]$t) {
  if ($t -le 0) { return 0.0 }
  if ($t -ge 1) { return 1.0 }
  return $t * $t * (3 - 2 * $t)
}

function Elev([double]$x, [double]$y) {
  # crater floor, tilting gently down to the east
  $z = -2568 + 0.8 * (9 - $x)

  # Delta outline traced from the HiRISE mosaic: an east-facing front that
  # turns into a south-facing front near (5.0, 2.3) km.
  $d1 = (5.08 + 0.333 * ($y - 2.55) + 0.10 * [math]::Sin($y * 2.6)) - $x
  $d2 = $y - (2.1 + 0.12 * [math]::Sin($x * 1.9 + 0.5))
  $d = [math]::Min($d1, $d2)
  # scarp is narrow (steep) except at the alluvial ramp on the south-east corner
  $rr = [math]::Sqrt([math]::Pow($x - 4.95, 2) + [math]::Pow($y - 2.35, 2))
  $w = 0.16 + 0.75 * [math]::Exp(-[math]::Pow($rr / 0.45, 2))
  $z += 72 * (Smooth ($d / $w + 0.5))
  if ($d -gt 0) { $z += 5 * [math]::Min($d, 3) }

  # Neretva Vallis inlet channel cut into the western delta top
  $yc = 4.3 + 0.25 * [math]::Sin($x * 1.4)
  $z -= 38 * [math]::Exp(-[math]::Pow(($y - $yc) / 0.22, 2)) * (Smooth ($d / 0.3)) * (Smooth ((2.6 - $x) / 0.6))

  # Kodiak remnant butte south of the delta front
  $rb = [math]::Sqrt([math]::Pow($x - 4.50, 2) + [math]::Pow($y - 1.17, 2))
  $z += 45 * (Smooth (1 - $rb / 0.22))

  # Belva secondary crater on the delta: bowl plus raised rim
  $rc = [math]::Sqrt([math]::Pow($x - 2.84, 2) + [math]::Pow($y - 3.60, 2))
  if ($rc -lt 0.38) { $z -= 60 * (1 - [math]::Pow($rc / 0.38, 2)) }
  $z += 12 * [math]::Exp(-[math]::Pow(($rc - 0.38) / 0.10, 2))

  # two small craters on the crater floor
  foreach ($cr in @(@(6.32, 2.26, 0.13, 12), @(7.66, 2.16, 0.15, 14))) {
    $rn = [math]::Sqrt([math]::Pow($x - $cr[0], 2) + [math]::Pow($y - $cr[1], 2))
    if ($rn -lt $cr[2]) { $z -= $cr[3] * (1 - [math]::Pow($rn / $cr[2], 2)) }
  }

  # dune ripples on the crater floor (Seitah)
  $rd = [math]::Sqrt([math]::Pow($x - 6.2, 2) + [math]::Pow($y - 3.25, 2))
  $z += 3 * [math]::Sin(($x * 0.8 + $y * 0.6) * 2 * [math]::PI / 0.25) * (Smooth (1.3 - $rd / 0.75))

  # rise toward the western crater rim
  if ($x -lt 1.0) { $z += 25 * [math]::Pow(1.0 - $x, 2) }

  # deterministic small-scale roughness
  $z += 1.2 * [math]::Sin($x * 7.3 + $y * 3.1) + 0.8 * [math]::Sin($x * 13.7 - $y * 11.9) + 0.5 * [math]::Sin($x * 23.1 + $y * 29.3)
  return [math]::Round($z, 1)
}

$inv = [System.Globalization.CultureInfo]::InvariantCulture
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append(@"
{
  "meta": {
    "name": "Jezero western delta - local elevation sample",
    "kind": "MODELED",
    "note": "Parametric approximation anchored to published MOLA / HiRISE-CTX DTM elevations for Jezero crater. Not a PDS data product. Generated by scripts/generate-dem.ps1.",
    "reference_products": [
      "JEZ_hirise_soc_006_DTM_MOLAtopography_DeltaGeoid_1m_Eqc_latTs0_lon0_blend40",
      "JEZ_ctx_B_soc_008_DTM_MOLAtopography_DeltaGeoid_20m_Eqc_latTs0_lon0"
    ],
    "units": "metres relative to the MOLA areoid"
  },
  "bounds": { "west": $west, "east": $east, "south": $south, "north": $north },
  "ncols": $ncols,
  "nrows": $nrows,
  "cellSizeM": { "x": 50.0, "y": 49.4 },
  "rowOrder": "north-to-south",
  "elevations": [

"@)

for ($r = 0; $r -lt $nrows; $r++) {
  $y = $heightKm * (1 - ($r + 0.5) / $nrows)
  $vals = New-Object string[] $ncols
  for ($c = 0; $c -lt $ncols; $c++) {
    $x = $widthKm * ($c + 0.5) / $ncols
    $vals[$c] = (Elev $x $y).ToString('0.0', $inv)
  }
  [void]$sb.Append('    [' + ($vals -join ',') + ']')
  if ($r -lt $nrows - 1) { [void]$sb.Append(',') }
  [void]$sb.Append("`n")
}
[void]$sb.Append("  ]`n}`n")

$out = Join-Path $PSScriptRoot '..\assets\data\jezero_dem_sample.json'
New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
[System.IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote $out ($ncols x $nrows cells)"
